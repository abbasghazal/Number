def automation_state(value):
    if str(value).startswith('flood_wait:'):
        return f"انتظار تيليجرام {value.split(':')[1]} ثانية"
    return AUTOMATION_STATES.get(value,JOB_NAMES.get(value,value))


def rule_preview(key,row):
    import json
    payload=json.loads(row[2])
    labels=[f'🤖 معاينة قاعدة #{key}',f'الرقم: +{row[0]}',f'الرد: {RULE_NAMES.get(row[1],row[1])}',
        f'الحالة: {"تعمل" if row[3] else "متوقفة"}',
        f'النطاق: {"خاص" if payload.get("scope","private")=="private" else "المجموعات المحددة"}',
        f'القالب: #{payload["template_id"]}' if payload.get('template_id') else f'النص: {payload.get("text","")}',
        f'المطابقة: {payload.get("match","لا تتطلب مطابقة")}',f'الأولوية: {payload.get("priority",50)}',
        f'منع التكرار: {payload.get("cooldown",3600)} ثانية',
        f'ساعات العمل: {payload.get("start_hour",0)}–{payload.get("end_hour",24)}؛ المنطقة: {payload.get("timezone","Asia/Baghdad")}',
        f'أيام الأسبوع (0 للاثنين): {payload.get("days",list(range(7)))}',
        f'المجموعات: {payload.get("chats",[])}',f'المحادثات المستثناة: {payload.get("exclude_chats",[])}',
        f'المرسلون المستثنون: {payload.get("exclude_senders",[])}','راجع الإعدادات ثم اختر تشغيل أو تعديل.']
    return '\n'.join(labels)


def job_preview(key,row,progress):
    import json
    from zoneinfo import ZoneInfo
    payload=json.loads(row[1])
    def local(value):
        return value.astimezone(ZoneInfo(row[4])).strftime('%Y-%m-%d %H:%M') if value else 'بلا نهاية'
    labels=[f'🗓 معاينة المهمة #{key}',f'المهمة: {JOB_NAMES.get(row[0],row[0])}',f'البداية: {local(row[2])}',
        f'النهاية: {local(row[3])}',f'المنطقة: {row[4]}',f'التكرار بالدقائق: {row[5] or "مرة واحدة"}',
        f'الحالة: {automation_state(row[6])}']
    names={'target':'الوجهة','text':'النص','template_id':'رقم القالب','first_name':'الاسم الأول','last_name':'اسم العائلة','about':'النبذة'}
    labels += [f'{names.get(k,k)}: {v}' for k,v in payload.items()]
    labels += [f'+{p}: {automation_state(s)}' for p,s in progress]
    labels += ['النتائج غير المحسومة تحتاج مراجعة يدوية قبل إنشاء محاولة جديدة.','راجع التفاصيل ثم اختر الإجراء.']
    return '\n'.join(labels)


